/**
 * Any failure that came from the database client rather than from application logic.
 * Lets a caller convert its own domain failures without swallowing a lock timeout or a
 * dropped connection, which the caller's own error mapping still needs to see.
 */
export function isPrismaError(error: any): boolean {
  return (
    error instanceof Prisma.PrismaClientKnownRequestError ||
    error instanceof Prisma.PrismaClientUnknownRequestError ||
    error instanceof Prisma.PrismaClientInitializationError ||
    error instanceof Prisma.PrismaClientRustPanicError
  );
}
